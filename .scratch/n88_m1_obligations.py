# -*- coding: utf-8 -*-
"""n+88：自看板萃取全部「M1 報告須…」之義務，落盤為可追溯清冊。

⚠️ 依 n+44「判準即產物，必須落盤版控」：本檔即萃取判準本身，
   清冊一律由本檔重跑產生，**不得手抄**（手抄即第九型缺陷）。
🚨 依 n+48 內容制衛生：輸出前過濾疑似文獻內容之行，寧可漏收也不落地標題。
⚠️ 行號為萃取當下之 COORDINATION.md 行號，會隨看板增長而位移；
   故清冊同時記錄**該行文字**，使其在行號失效後仍可 grep 回溯。
"""
import io
import re
import subprocess

BOARD = 'COORDINATION.md'
OUT = 'docs/m1-obligations.md'

# 🚨 第一版把「可支持 M1 討論**建議值**之歷史演變」抓成義務——
#    「建議」在該處是劑量術語「建議值」的一部分，不是義務動詞。
#    修正後分兩類，且兩類互斥：
#
# （一）報告義務：M1 報告本身必須做的事
OBLIGATION = re.compile(
    r'M1[^。]{0,30}(報告[^。]{0,20})?'
    r'(須|應|必須|不得|清償|呈交|揭露|載明|明列|列出|記錄為)')
# 排除「建議值」「建議量」等術語誤傷（不含義務動詞時不予收錄）
NOT_OBLIGATION = re.compile(r'建議(值|量|攝取|範圍)')

# （二）素材線索：某筆記錄可供 M1 某章節引用——不是義務，但不可遺失
MATERIAL = re.compile(r'(可支持|可供|供|對)\s*M1|M1\s*(之|的)?\s*(討論|敘事|實務落地|契約審)')


# ── n+136：兩個新樣式 ──────────────────────────────────────────────
# 🚨（一）回聲過濾。清冊重跑於第 446 輪查出一件事：**看板現在大量談論清冊本身**，
#    於是擷取器把「引用某條義務」的行當成新義務收進來——第 446 輪重跑之 8 條「新義務」
#    **全部都是回聲**，沒有一條是真的新義務。
#    ⚠️ 濾的是「清冊自身的形狀」（索引行、清冊表格列、談論清冊之語句），
#    🚫 不是憑「看起來像引用」猜——那會誤傷真義務（實測會多砍 3 條）。
ECHO = re.compile(
    r'^[甲乙丙丁戊己庚辛壬檢待]\s+\d{4,5}\s'      # 清冊索引之回聲
    r'|^\|\s*\d{4,5}(?:／\d{4,5})*\s*\|'        # 清冊表格列之回聲
    r'|義務清冊|本義務')                             # 談論清冊本身

# 🚨（二）明示標記。同一輪查出更嚴重的事：**擷取器逐行比對，
#    而協調者裁定把「M1」與義務動詞寫在不同行**（換行是為了可讀），
#    於是近 4,400 行裡單行即符合樣式者僅 8 條，且全是回聲。
# ⚠️ **🚫 不放寬樣式**——本 run 已因放寬吃過兩次虧（建議值／應）。
# ✅ 改為：裁定若創設 M1 報告義務，須自帶標記；擷取器只認這個標記，不猜。
MARKER = '📌 M1 義務'
# ⚠️ 標記須在行首（去除 markdown 記號後），🚫 不得只是句中提到它——
# 🚨 否則「說明標記怎麼用」的那句話會被當成一條義務（實測真的發生了）。
# ✅ 自 n+136 之裁定起，猜測式樣式不再新增義務：**該裁定以後的看板只認標記。**
# 🚨 理由是第 446 輪查到的複利效應：看板談論清冊，清冊就擷取自己的倒影。
CUTOFF_HEADING = '## 🧭 協調者裁定 n+136'


def _marked(line):
    return line.lstrip('*>#- 　').startswith(MARKER)

# 內容制衛生：疑似逐字標題（同 n+85 公布之樣式）
TITLE = re.compile(r'〈([^〉]{25,300})〉')
TITLE_INNER = re.compile(r'[A-Za-z]{4,}\s+[A-Za-z]{4,}')


# ── n+134：兩個非章節類別改用非天干代號 ────────────────────────────
# 🚨 天干代號在本 run 指「M1 報告的章節」。而以下兩類都不是章節：
#   「措辭與計數規則」是檢查表（n+81 61919 明訂：須逐條套用於每一節，
#    🚫 不是獨立成節）；「未分類」是待歸類暫存區。
# ⚠️ 兩者原本各佔一個天干（庚、戊），於是「庚」同時指清冊的措辭規則
#    與文件集的 harms 一節——**同代號異義，且兩者皆在用**。
# ✅ 故改為「檢」與「待」。舊名保留於此以便回溯：
#      檢 · 措辭與計數規則  →  檢 · 措辭與計數規則
#      待 · 未分類（須人工歸類） → 待 · 未分類（須人工歸類）
# ──────────────────────────────────────────────────────────────────
# 分類：依關鍵詞歸入 M1 報告之四節
SECTIONS = [
    ('甲 · 檢索與涵蓋完整性',
     ('檢索', '涵蓋', '完整性', '漏', 'lane', '流程圖', '去重', '碰撞')),
    ('乙 · 判讀方法與其限制',
     ('判讀', '判準', '摘要', 'title-only', '標題', '契約', '軸', '重篩', '盲測')),
    ('丙 · 統計終止與抽驗',
     ('終止', '抽驗', 'pScore', '絆網', 'ADR-0008', '母體', '未篩')),
    ('丁 · 稽核債與流程品質',
     ('抽查債', '債', '稽核', '撤稿', '勘誤', '衛生', '更正', 'retract',
      '清償', '記帳', 'ownerAuditQueue')),
    ('己 · 呈現與交付通則（跨章節）',
     ('交付', '筆數規則', '呈現', '重跑', '沿用', '不得以單一數字')),
]


# 🚨 n+89 人工歸類（依 n+88 巡檢指示「不得由程式推定」）。
#    讀過戊類全部條目後逐條指定，以「原文中之特徵片語」為鍵——
#    ⚠️ 不以行號為鍵，因行號隨看板增長而位移。
#    🚨 讀完才發現：最大一群不是分類器缺關鍵詞，是**我缺一個類別**——
#    它們全在規定「同一件事在報告裡該怎麼寫」，而非規定報告要寫什麼。
MANUAL = [
    # (特徵片語, 歸屬類別)
    ('方向不一致', '檢 · 措辭與計數規則'),
    ('皆為陰性', '檢 · 措辭與計數規則'),
    ('正式表述定為', '檢 · 措辭與計數規則'),
    ('表述須再次更新', '檢 · 措辭與計數規則'),
    ('逐筆分流', '檢 · 措辭與計數規則'),
    ('作為族群大小', '檢 · 措辭與計數規則'),
    ('覆蓋率驗證', '甲 · 檢索與涵蓋完整性'),
    ('方法學品質', '乙 · 判讀方法與其限制'),
    ('性別代表性', '乙 · 判讀方法與其限制'),
    ('從未單獨作為排除理由', '乙 · 判讀方法與其限制'),
    ('不可回溯', '乙 · 判讀方法與其限制'),
    ('數值門檻', '乙 · 判讀方法與其限制'),
]

MANUAL_ORDER = ['檢 · 措辭與計數規則']


def classify(text):
    # 人工歸類優先於關鍵詞
    for phrase, name in MANUAL:
        if phrase in text:
            return name
    for name, keys in SECTIONS:
        if any(k in text for k in keys):
            return name
    return '待 · 未分類（須人工歸類）'


def main():
    lines = io.open(BOARD, encoding='utf-8').read().split('\n')
    rows, material, skipped = [], [], 0
    echoes = []
    cutoff = next((i + 1 for i, l in enumerate(lines)
                   if l.startswith(CUTOFF_HEADING)), len(lines) + 1)
    for n, raw in enumerate(lines, 1):
        line = raw.strip()
        if 'M1' not in line:
            continue
        # 內容制衛生過濾（兩類共用）
        if any(TITLE_INNER.search(m) for m in TITLE.findall(line)):
            skipped += 1
            continue
        # 🚨 素材優先：「可支持 M1 討論劑量帶**應**以絕對量」句中之「應」
        #    屬被討論內容，不是報告義務。先判素材，可避免此類誤收。
        # ⚠️ 順序要緊：ECHO 只用來**壓下已被判為候選者**，
        # 🚫 不得放在最前面當總濾網——那會連「從未被收」的行也算進回聲數，
        # 🚨 且會安靜吃掉一條剛好含「本義務」字樣的真義務。
        if _marked(line):
            rows.append((n, line))          # ✅ 明示標記，🚫 不再猜
        elif n >= cutoff:
            # 🚨 n+136 之後不再以樣式新增義務——只認標記。
            continue
        elif MATERIAL.search(line):
            (echoes if ECHO.search(line) else material).append((n, line))
        elif OBLIGATION.search(line) and not NOT_OBLIGATION.search(line):
            (echoes if ECHO.search(line) else rows).append((n, line))

    buckets = {}
    for n, line in rows:
        buckets.setdefault(classify(line), []).append((n, line))

    head = subprocess.run(['git', 'rev-parse', '--short', 'HEAD'],
                          capture_output=True, text=True).stdout.strip()
    out = [
        '# M1 報告義務清冊',
        '',
        '**本檔由 `.scratch/n88_m1_obligations.py` 自 `COORDINATION.md` 重跑產生，'
        '不得手動編輯。**',
        '',
        f'- 萃取自看板 commit `{head}`，共 **{len(lines)}** 行',
        f'- **報告義務 {len(rows)} 條**（M1 報告本身必須做的事）',
        f'- **素材線索 {len(material)} 條**（某筆記錄可供某章節引用，不是義務）',
        f'- 因疑似含逐字文獻標題而略過 **{skipped}** 條'
        '（內容制衛生，n+48／n+85 樣式）',
        f'- 🚨 **濾除清冊自身之回聲 {len(echoes)} 條**（n+136）——'
        '看板現在大量談論清冊本身，引用某條義務的行會被誤收為新義務。',
        '',
        '🚨 **兩類必須分開，且分錯過兩次**：第一版把「可支持 M1 討論**建議值**'
        '之歷史演變」收成義務——「建議」在該處是劑量術語的一部分；第二版又把'
        '「可支持 M1 討論劑量帶**應**以絕對量」收成義務——該「應」屬被討論的內容。'
        f'**混在一起，{len(rows)} 條真義務會被 {len(material)} 條素材淹沒。**',
        '',
        '⚠️ **行號會隨看板增長而位移**；每條同時保留原文，'
        '行號失效時以原文 grep 回溯。',
        '',
        '✅ **勾稽已改以原文指紋為鍵（n+136）**：`n116_obligation_crosscheck.py` '
        '不再以行號配對，故本檔重跑後**不會使全部義務同時失聯**；'
        '其自我稽核丙每輪模擬一次行號位移以證明此事。',
        '',
        '⚠️ **兩個非章節類別不佔天干（n+134）**：措辭與計數規則是檢查表'
        '（須逐條套用於每一節，🚫 不是獨立成節）、未分類是暫存區，'
        '故代號為「檢」與「待」。**舊名為「庚」「戊」，看板早期引用以舊名為準。**',
        '',
        '⚠️ **本清冊只負責「不漏」，不負責「已辦」**——'
        '勾稽狀態須於 M1 撰寫時逐條標註，不得由本檔推定。',
        '',
    ]
    ordered = SECTIONS + [(n, ()) for n in MANUAL_ORDER] + \
        [('待 · 未分類（須人工歸類）', ())]
    for name, _ in ordered:
        items = buckets.get(name)
        if not items:
            continue
        out += [f'## {name}', '', f'共 {len(items)} 條。', '',
                '| 看板行 | 義務原文 |', '|---|---|']
        for n, line in items:
            out.append('| %d | %s |' % (n, line.replace('|', '\\|')))
        out.append('')

    out += ['---', '', '## 附錄 · 素材線索（非義務）', '',
            f'共 {len(material)} 條。**這些不是報告義務**，是判讀過程中標記為'
            '「某章節可引用」的記錄。**列此以免遺失，但不得當成待辦清單。**', '',
            '| 看板行 | 原文 |', '|---|---|']
    for n, line in material:
        out.append('| %d | %s |' % (n, line.replace('|', '\\|')))
    out.append('')

    io.open(OUT, 'w', encoding='utf-8').write('\n'.join(out))
    print('✅ 已產生 %s' % OUT)
    print('   報告義務 %d 條、素材線索 %d 條、衛生過濾略過 %d 條'
          % (len(rows), len(material), skipped))
    print('   🚨 濾除回聲 %d 條（n+136）' % len(echoes))
    for name, _ in ordered:
        if buckets.get(name):
            print('   %-24s %d 條' % (name, len(buckets[name])))


if __name__ == '__main__':
    main()
