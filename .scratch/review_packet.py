def main():
    m = _measured()
    text = TEMPLATE.format(board_mb=m["board_bytes"] / 1e6, **m)
    OUT.write_text(text, encoding="utf-8")
    size = len(text)
    # ⚠️ 中文約每 1.0–1.5 字一個 token，🚫 故不給單一數字（看板 49308）。
    lo, hi = size / 1.5, size / 1.0
    b_lo, b_hi = m["board_chars"] / 1.5, m["board_chars"] / 1.0
    print("✅ 已寫出 %s" % OUT)
    print()
    print("   %d 字元 → 約 %.1f–%.1f 千 token" % (size, lo / 1000, hi / 1000))
    print("   ⚠️ 對照：看板 %d 字元 → 約 %.0f–%.0f 萬 token"
          % (m["board_chars"], b_lo / 10000, b_hi / 10000))
    print("   🚨 **差約 %d 倍。🚫 不要貼看板。**" % round(m["board_chars"] / size))
    print()
    print("🚨 貼這一份就好，🚫 不要附程式碼、🚫 不要附看板。")
    print("⚠️ 資料包裡已經寫明「你看不到什麼」，故對方不會假裝看得到。")
