def direction_quote():
    """🚨 方向分布之正式表述（n+90），**不得再簡化**——自骨架抽取。

    ⚠️ 只取第一個連續引用區塊（n+157 三之教訓）。
    """
    t = SKELETON.read_text(encoding="utf-8")
    block = t.split("**現行正式表述**（n+90，不得再簡化）：", 1)[1]
    lines = []
    for l in block.split("\n"):
        if l.startswith("> "):
            lines.append(l)
        elif lines:
            break
    if len(lines) != 3:
        raise ValueError(f"🚨 該表述應為 3 行，取到 {len(lines)} 行——⚠️ 骨架已變")
    return "\n".join(lines)


