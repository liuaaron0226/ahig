    from pathlib import Path
    _src = Path(".scratch/n116_obligation_crosscheck.py").read_text(encoding="utf-8")
    _ns = {}
    exec("ANCHORS = {" + _src.split("ANCHORS = {", 1)[1].split("\n}\n", 1)[0]
         + "\n}", _ns)
    r, d, k = tally(_ns["ANCHORS"])
    print(f"條目 {r}｜重述 {d}｜**相異義務 {k}**")
    print("🚨 「N／N 涵蓋」之 N 是條目數，🚫 不得讀成相異義務數。")
