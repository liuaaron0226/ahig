"""義務清冊之**判準單一來源**——🚨 「這一條是不是重述」只准有一個答案。

## 🚨 這支存在的理由：兩支程式各自數同一件事，數出不同的答案

第 469 輪發現：`n116` 印「重述 **17**／相異義務約 **65**」，
而 `n154` 之 `OBLIGATION_RESTATED` 現算得 **10**、`OBLIGATION_DISTINCT` 得 **72**。
**⚠️ 兩者量的是同一個東西，卻沒有任何一道檢查把它們對過。**

**🚨 而更要緊的是：兩邊都錯，且錯在相反方向。**

| | 規則 | 結果 | 錯在哪 |
|---|---|---|---|
| `n116` | `'重述' in lab or lab.startswith('同')` | 17 | ⚠️ **多算 1**：「同試驗分裂之兩筆一併處理」是一條**實質義務**，只是碰巧以「同」起頭 |
| `n154` | 整個 tuple 含 `'重述'` 或 `'同上'` | 10 | ⚠️ **少算 6**：清冊裡「同 68」「同 48466」是**「同上」的簡寫**，指向看板行號 |

**✅ 正解 16**（4 條「重述」＋5 條「同上」＋1 條「同上（第二處）」＋6 條「同 <看板號>」），
**故相異義務為 82 − 16 ＝ 66。**

## ⚠️ 這一型的教訓，🚫 不是「規則寫錯了」

**🚨 是「同一個量有兩份實作，而沒有人把它們相減過」。**
兩份實作各自都看起來合理，各自都通過自己的檢查，
**⚠️ 差異只有在把兩個數字並排時才看得見**——而在此之前，
`n154` 的數字還被寫進同值異義登記簿，成為「四個不相干的 10」的一員。
**🚫 一個錯的數字，被登記成了一項「已查核」的巧合。**

> **✅ 故本檔把判準抽成單一來源**，兩支程式一律 import 此處，
> 且 `n131` 新增一道「兩邊必須相等」的交叉檢查（🚨 本次遺漏的正是那一道）。

## 🚨 「同 <數字>」為何算重述，而「同試驗…」不算

⚠️ 兩者都以「同」起頭，**🚫 而字首不是判準**：

  - **「同 48466」**：整個 label 就只有「同」加一個看板行號——
    它不敘述任何義務，**只說「這一條就是上面那一條」**。✅ 是重述。
  - **「同試驗分裂之兩筆一併處理」**：「同」是「同一個試驗」的同，
    整句敘述了一件要做的事。**🚫 不是重述。**

**⚠️ 故判準是「label 是否僅為一個指向」，不是字首比對。**

🚫 本檔不得改為「凡以同起頭者皆重述」——那正是 `n116` 犯過的錯。
"""

import re

# 🚨 「同上」之簡寫形式：整個 label 僅為「同」加看板行號，🚫 不含任何敘述。
#    ⚠️ 允許「同 68」「同68」；🚫 不允許「同 68 之延伸」——那多了敘述，須逐條判。
_POINTER_ONLY = re.compile(r"^同\s*\d+$")


def is_restatement(label):
    """本條是否為既有義務之重述／指向。

    🚨 **只看 label**，🚫 不掃描替代語句（`alts`）——
    ⚠️ alts 是「這條義務在文中可能長什麼樣」的比對用詞，
    其中偶然出現「重述」二字**不代表本條是重述**。
    """
    lab = str(label).strip()
    return ("重述" in lab
            or "同上" in lab
            or bool(_POINTER_ONLY.match(lab)))


def tally(anchors):
    """回傳（條目數, 重述數, 相異義務數）。

    🚨 三者由同一份判準算出，🚫 呼叫端不得各自再減一次。
    """
    rows = len(anchors)
    restated = sum(1 for v in anchors.values() if is_restatement(v[1]))
    return rows, restated, rows - restated


# ── 🚨 反向對照：判準須在**兩個方向**上都被試過（n+134）─────────────
# ⚠️ 只證明它抓得到重述是不夠的——本次的錯正是「抓到了不該抓的」。
_MUST_HIT = ["同上", "同上（第二處）", "同 68", "同48466",
             "檢類重述；n+134 前稱庚類"]
_MUST_MISS = ["同試驗分裂之兩筆一併處理", "同一批 33 筆逐筆回看",
              "不得寫皆為陰性"]

for _s in _MUST_HIT:
    assert is_restatement(_s), f"🚨 判準漏抓應為重述者：{_s!r}"
for _s in _MUST_MISS:
    assert not is_restatement(_s), f"🚨 判準誤抓實質義務為重述：{_s!r}"


