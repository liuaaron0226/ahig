# 🚨 三種「沒有值」，各有各的標記——🚫 不得共用一個。
NOT_YET = "⚠️〔全文取得後才存在〕"
NEEDS_EXEC = "⚠️〔待執行室量測〕"


def v(name):
    try:
        return f"{_n154.value(name)}"
    except Exception:                                  # noqa: BLE001
        return NOT_YET if name == "HARMS_S5_ACTUAL" else NEEDS_EXEC


def quota_quote():
    """🚨 看板 62967 之裁示原句，須照抄。

    ⚠️ 依 n+157 三：只取第一個連續引用區塊，🚫 不掃到檔尾。
    ⚠️ 而該引句內含 `{{HARMS_S5_QUOTA}}`——**須代入現算值**，
    🚫 骨架用的佔位符不得原樣出現在成稿裡。
    """
    t = SKELETON.read_text(encoding="utf-8")
    block = t.split("## 一、🚨 本節的主命題", 1)[1]
    lines = []
    for l in block.split("\n"):
        if l.startswith("> "):
            lines.append(l)
        elif lines:
            break
    if len(lines) != 2:
        raise ValueError(f"🚨 該裁示原句應為 2 行，取到 {len(lines)} 行"
                         "——⚠️ 骨架已變，🚫 不得逕自續用")
    out = "\n".join(lines).replace("{{HARMS_S5_QUOTA}}", f"**{v('HARMS_S5_QUOTA')}**")
    if "{{" in out:
        raise ValueError(f"🚨 引句仍含未代入之佔位符：{out}")
    return out


