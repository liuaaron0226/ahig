def quoted_ban():
    """🚨 看板 63655 之原句，須照抄。

    ⚠️ 依 n+157 三之教訓：**只取第一個連續引用區塊**，
    🚫 不得「取此後所有以 `> ` 開頭的行」——那會一路掃到檔尾。
    """
    t = SKELETON.read_text(encoding="utf-8")
    block = t.split("## 一、🚫 全節第一禁令", 1)[1]
    lines = []
    for l in block.split("\n"):
        if l.startswith("> "):
            lines.append(l)
        elif lines:
            break
    if len(lines) != 2:
        raise ValueError(f"🚨 該禁令應為 2 行，取到 {len(lines)} 行"
                         "——⚠️ 骨架已變，🚫 不得逕自續用")
    return "\n".join(lines)


