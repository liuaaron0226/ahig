"""產生**辛節成稿**：`docs/m1-g-acquisition-report.md`。

## 🚨 本節是全 M1 最容易被讀錯的一節

它談「我們拿不到多少全文」，**⚠️ 而讀者極易把它讀成「這個題目沒什麼研究」。**
辛節骨架第一條禁令就是這個，且來自看板 63655 原句：
**文獻存在，是付費牆後。**

## ⚠️ 而本節裡有兩個不同的「拿不到」，成因相反

- **缺口**：不在開放取用之內（付費牆後）。
- **遭擋**：在開放取用之內，但出版社擋自動化抓取。

**🚨 混寫會得到一句兩頭都不對的話**：把遭擋說成付費牆，低估可補救性；
把缺口說成「只是被擋」，高估可補救性。

## 🚨 本節含本 run 最危險的一對同值

`LANDING_ROUTE_N`（路徑分類）與 `LANDING_REACHED`（當時抓得到）**皆為 16**，
**⚠️ 而實測交集僅 6 筆。**
**🚫 故「16 筆走著陸頁路徑，其中 16 筆可達」為禁句**——由 `n158` 之③擋。

Run:  python3 .scratch/n159_section_g_report.py
"""

