def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, str(Path(path)))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


_n154 = _load("n154", ".scratch/n154_cell_producer.py")
