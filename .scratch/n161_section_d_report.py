"""產生**丁節成稿**：`docs/m1-d-audit-debt-report.md`。

## 🚨 這一節是擁有者唯一真正判得動的一節

依 ADR-0009，擁有者不是領域專家、不讀英文文獻。
**⚠️ 他判不了「這些文獻的結論對不對」——但他判得了「這個流程可不可信」。**
**🚨 故本節之呈現方式，比本節的內容更要緊。**

## ⚠️ 而本節最容易被讀成兩種相反的錯

| 誤讀 | 為何會發生 | 怎麼擋 |
|---|---|---|
| 「他們錯了十幾次，這報告不能信」 | 型錄整張表都是自承的錯 | 🚨 併呈**守住的界線**，且說明「抓得到才列得出」 |
| 「他們有一套會自我糾錯的流程」 | 型錄看起來像一套偵測器 | 🚫 明寫**能糾錯的是兩室互查的安排，不是任何一方** |

**🚨 兩種誤讀都會使他做出錯的決定**，故兩者都要主動擋。

## 🚨 型錄要讀的是**分布**，不是條數

⚠️ 「誰抓到的」那一欄才是重點：
**若全部都是自曝，讀者有理由懷疑只是挑好講的講；
若全部靠他人抓，代表自我檢查沒有作用。**

**⚠️ 而條數本身有一個陷阱**：表格列數 ≠ 型數（有一列是舊型再現）。
**🚫 本檔兩者分別現數，不寫死。**

Run:  python3 .scratch/n161_section_d_report.py
"""

import datetime as _dt
import importlib.util
import sys
from collections import Counter
from pathlib import Path

import signal
try:
    signal.signal(signal.SIGPIPE, signal.SIG_DFL)
except (AttributeError, ValueError):
    pass

OUT = Path("docs/m1-d-audit-debt-report.md")
SKELETON = Path("docs/m1-d-audit-debt-skeleton.md")
CATALOGUE_HEADER = "| # | 缺陷型 | 誰抓到 | **靠什麼抓到** |"


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, str(Path(path)))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


_n154 = _load("n154", ".scratch/n154_cell_producer.py")
lint = _load("n158", ".scratch/n158_report_lint.py")

NEEDS_EXEC = "⚠️〔待執行室量測〕"


def v(name):
    try:
        return f"{_n154.value(name)}"
    except Exception:                                  # noqa: BLE001
        return NEEDS_EXEC


def catalogue():
    """自骨架現讀型錄。

    🚨 **🚫 不寫死型數**——⚠️ 本 run 每隔幾輪就新增一型，
    而寫死的數字不會跟著長（型錄自己的第 12 型）。

    ⚠️ 回傳 (列數, 型數, 誰抓到之分布)。
    **🚨 列數與型數不同**：有一列是舊型再現，🚫 不是新型。
    """
    t = SKELETON.read_text(encoding="utf-8")
    if CATALOGUE_HEADER not in t:
        raise ValueError("🚨 骨架中找不到型錄表頭——⚠️ 表格已改，🚫 不得逕自續用")
    blk = t.split(CATALOGUE_HEADER, 1)[1]
    rows = []
    for line in blk.split("\n"):
        line = line.strip()
        if not line:
            continue
        if not line.startswith("|"):
            break
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) >= 4 and not set(cells[0]) <= set("-: "):
            rows.append(cells)
    if not rows:
        raise ValueError("🚨 型錄表解析出 0 列——⚠️ 格式已變")

    # ⚠️ 「再現」列不計為新型：其編號欄不是純數字。
    kinds = [r for r in rows if r[0].strip().isdigit()]

    def who(s):
        # 🚨 「兩室各抓到一例」須先判——⚠️ 它含「室」字，
        # 若不先攔，會被整列算成「另一室抓到」，**而那不是事實**。
        if "兩室" in s:
            return "兩個工作室各抓到一例"
        if "自曝" in s:
            return "執行室自己招出來的"
        if "另一室" in s or "執行室" in s:
            return "另一個工作室抓到的"
        if "錯誤訊息" in s:
            return "程式自己噴錯攔下的"
        return "我自己回頭檢查發現的"

    return len(rows), len(kinds), Counter(who(r[2]) for r in rows)


def report():
    now = _dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    n_rows, n_kinds, dist = catalogue()
    L = []
    A = L.append

    A("# 丁：這個流程犯過什麼錯，又守住了什麼")
    A("")
    A(f"**產生時刻：{now}**　"
      "（⚠️ 本節數字於產生當下由權威來源現算，🚫 未沿用任何一輪之值）")
    A("")
    A("> **這一節怎麼讀**：每一小段的第一句話是結論，用日常語言寫的。"
      "接在後面的是給稽核者查證用的依據。")
    A("")
    A("---")
    A("")

    # ── 一 ────────────────────────────────────────────────────
    A("## 一、先講這一節該怎麼用")
    A("")
    A("**一句話**：這一節是整份報告裡**你最判得動的一節**。")
    A("")
    A("你沒辦法自己去判斷那些文獻的結論對不對——**那要讀英文、要懂這個領域**。"
      "**但你判得動「這個流程可不可信」**，而這一節就是給你判這件事的材料。")
    A("")
    A("**⚠️ 而它很容易被讀成兩種相反的錯，兩種都會讓你做出錯的決定**：")
    A("")
    A("| 如果你讀成 | 那是錯的，因為 |")
    A("|---|---|")
    A("| 「他們錯了十幾次，這報告不能信」 | **能列出來的錯，都是被抓到的錯**"
      "——一份沒有錯誤清單的報告，通常不是沒犯錯，是沒在看 |")
    A("| 「他們有一套會自我糾錯的流程」 | **🚫 沒有這種東西。**"
      "會糾錯的是「兩個工作室互相檢查＋規則先寫下來＋刻意放假資料試探」這個安排，"
      "**不是其中任何一方** |")
    A("")

    # ── 二 ────────────────────────────────────────────────────
    A("## 二、錯誤清單：要看的是「誰抓到的」，不是「有幾條」")
    A("")
    A("**一句話**：我們把每一次犯的錯都記下來，"
      "**而最有用的欄位是「這個錯是誰發現的」。**")
    A("")
    A(f"目前清單有 **{n_rows}** 列，其中 **{n_kinds}** 種是不同型的錯"
      "（**⚠️ 有一列是舊型又犯了一次，🚫 不算新型**）。")
    A("")
    A("**發現來源的分布：**")
    A("")
    A("| 是誰發現的 | 幾次 |")
    A("|---|---|")
    for k, n in dist.most_common():
        A(f"| {k} | **{n}** |")
    A("")
    A("**⚠️ 這個分布要這樣讀**：")
    A("")
    A("- **如果全部都是自己招的**，你有理由懷疑只挑了好講的講。")
    A("- **如果全部都是別人抓到的**，代表自我檢查根本沒作用。")
    A("- **四種來源都有，才表示這幾道檢查是真的在各自運作。**")
    A("")
    A("> **🚨 而其中有一列的抓法是「憑直覺覺得這個數字不對」。**"
      "**⚠️ 那一列若佔比升高，代表檢查有盲區，🚫 不代表直覺很準。**")
    A("")
    A("**⚠️ 上表的歸類是用關鍵字自動分的，須說明它的粗糙處**："
      "同一列若橫跨兩種來源，只會被歸進一格。"
      "**🚨 故這張表看的是「四種來源都有」這件事，"
      "🚫 不是拿其中某一格的數字去做比較。**")
    A("")

    # ── 三 ────────────────────────────────────────────────────
    A("## 三、還沒查完的抽查工作")
    A("")
    A("**一句話**：我們給自己記了一本帳，"
      "**列出哪些地方應該再抽查一次確認**。")
    A("")
    A("| | 項目數 |")
    A("|---|---|")
    A(f"| 累計記過 | **{v('DEBT_CUMULATIVE')}** |")
    A(f"| 已經查完 | **{v('DEBT_SETTLED')}** |")
    A(f"| **還欠** | **{v('DEBT_OUTSTANDING')}** |")
    A("")
    A("**🚨 這裡的「項」是「抽查工作」，不是「文獻篇數」。**")
    A("")
    A("這一點必須講清楚，因為報告別處會出現「這一批抽查了幾十篇文獻」這種句子——"
      "**⚠️ 那是「篇」，這裡是「項」。**"
      "**🚫 兩個數字並排而不標單位，會被讀成互相矛盾。**")
    A("")
    A("**⚠️ 而且「還欠」和「累計」要一起報。**"
      "只報「還欠幾項」，你會以為總共就只抽查過那幾項。")
    A("")
    A("### 影子對帳（完整交代，🚫 不只報結論）")
    A("")
    A("篩選期間我們讓兩套判讀並行，再逐筆對帳：")
    A("")
    A(f"- 兩邊一致、直接成為正式決定的：**{v('SHADOW_CONCORDANT')}** 筆")
    A(f"- 兩邊不一致、進入待人工覆核佇列的：**{v('SHADOW_QUEUED')}** 筆")
    A("")
    A("**⚠️ 一致的那批「正式篩選不再重判」**——"
      "理由是兩個判讀者已經一致，重判不會帶來新資訊。"
      "**🚨 這是一個設計選擇，不是省略，故須寫明。**")
    A("")

    # ── 四 ────────────────────────────────────────────────────
    A("## 四、守住的界線——**這一格比錯誤清單更難，也更該看**")
    A("")
    A("**一句話**：錯誤清單講的是「哪裡沒守住」，"
      "**這一格講的是「哪裡本來會出錯，但停住了」。**")
    A("")
    A("**⚠️ 只給錯誤清單，你會只看到偵測能力，"
      "看不到有沒有在該停的時候停住。**")
    A("")
    A("### 第一則：拒絕把一個成功率套到另一批東西上")
    A("")
    A("先前有 11 篇被網站擋掉，我們改試「同一篇論文的其他位址」，**救回 4 篇**。")
    A("")
    A("後來又有另外 12 篇從來沒試過。"
      "**⚠️ 照理可以說「照 4／11 的比例，大概還能救回 4 篇」。**")
    A("")
    A("**🚫 而執行室拒絕這樣推**，理由是：前一批是**出版社擋自動化、別處有副本**；"
      "**後一批本身就已經在副本那一端了**——**兩批不是同一種東西**。")
    A("")
    A("| | 篇數 |")
    A("|---|---|")
    A("| 若照比例外推，預測再救回 | 約 **4** |")
    A("| **實際去試，救回** | **0** |")
    A("")
    A("> **🚨 那條界線如果沒守住，報告會多出四篇根本不存在的可取全文。**")
    A("> **⚠️ 而它不是靠任何檢查攔下來的**——"
      "是靠先問一句「這兩批是不是同一種東西」。")
    A("")
    A("**✅ 這件事可以寫成一條通則**："
      "**一個方法的成功率，其實是「它的前提成立的比率」，"
      "🚫 不是這個方法本身有多好。**")
    A("")
    A("### 第二則：沒有順手把後面那道檢查的答案先寫好")
    A("")
    A("有兩個小層在抽樣時合併，**它們的區分依設計要留到讀全文時才做**。"
      "而全文已經部分到手，取得階段**其實有能力現在就先分好**——**它沒有分。**")
    A("")
    A("理由是：判斷「腸胃不適是不是主要結果」要讀全文，那是下一階段的工作；"
      "**而那個判斷本身，正是這一層要量的東西。**")
    A("")
    A("> **🚨 若取得階段順手分好，那一層就什麼都量不到了**——"
      "因為它要量的正是「下一階段分不分得出來」。")
    A("")
    A("**⚠️ 這一則比第一則難**：第一則是拒絕外推，有現成規則可循；"
      "**🚨 這一則是察覺「我這一步做下去，會把後面那個檢查的答案先寫好」**"
      "——**而沒有任何規則會提醒你，因為那一步本身完全合法。**")
    A("")

    # ── 五 ────────────────────────────────────────────────────
    A("## 五、三件必須跟著寫的話")
    A("")
    A("1. **「抓得到錯」不等於「已經沒有錯」。**"
      "清單最後幾項都是最近幾輪才加進去的——"
      "**🚨 還在增加，就表示同型的錯很可能還有沒被發現的。**")
    A("")
    A("2. **抓到的都是「程式或比對驗得出來」的錯。**"
      "**⚠️ 判讀本身判對判錯，不在這張清單裡**——"
      "那要靠抽查與影子對帳，而抽查還沒查完。")
    A("")
    A("3. **🚫 不可以寫成「這個流程能自我糾錯」。**"
      "能糾錯的是那個**安排**：兩個工作室互查、規則先落盤、"
      "以及刻意放進假資料看檢查會不會叫。"
      "**⚠️ 任何單獨一方都做不到。**")
    A("")
    return "\n".join(L)


text = report()
_prev = OUT.read_text(encoding="utf-8") if OUT.exists() else None
_strip = lambda s: "\n".join(l for l in s.split("\n")
                             if not l.startswith("**產生時刻："))
changed = _prev is not None and _strip(_prev) != _strip(text)
OUT.write_text(text, encoding="utf-8")
print(f"{'🆕 首次產生' if _prev is None else ('⚠️ 內容有變（值漂移或被手改）' if changed else '✅ 內容未變')}"
      f" {OUT}（{len(text.splitlines())} 行）")
print(f"⚠️ 缺口標記 {text.count(NEEDS_EXEC)} 處（🚨 私有根不可及，🚫 不以舊快照代填）")

problems, controls = lint.run(
    text, _n154.COINCIDENCE, _n154.value,
    forbidden_phrases=("本流程能自我糾錯",))
sys.exit(1 if lint.report(problems, controls, "丁節成稿自檢") else 0)
