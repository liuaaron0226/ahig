def _lineending():
    """（換行轉換後會失效之份數, 總份數）——🚨 自產物現讀，🚫 不打字。

    ⚠️ 這兩個數之所以要現讀而不寫死：**它們是我預測錯的那一次的證據**，
    🚨 而一個寫死的證據會在來源改變後繼續宣稱同一件事。
    """
    import json
    d = json.loads(Path(".scratch/n514_hash_lineending_exposure.json")
                   .read_text(encoding="utf-8"))
    exposed, total = d["wouldMismatchAsCrlf"], d["total"]
    # 🚨 併查反向：⚠️ 若「今日兩式相等」不再成立，本段之敘述即失效，
    #    🚫 不得照印——那時要講的是另一件事。
    if d["rawEqualsNormalisedToday"] != total:
        raise ValueError(
            f"🚨 今日已非全部相等（{d['rawEqualsNormalisedToday']}／{total}）"
            "——⚠️ 本節「現在確實一樣」那句話已不成立，🚫 不得續用")
    if not 0 <= exposed <= total:
        raise ValueError("🚨 曝險份數超出母體")
    return exposed, total


_LINEENDING_EXPOSED, _LINEENDING_TOTAL = _lineending()


def _rest_debt():
    """尚欠項中非「影子歧異」的那一部分。

    🚨 **由兩格相減得出，🚫 不打字**——看板記為「w2 5 ∪ 影子尚欠 11」，
    ⚠️ 而聯集之所以等於相加，是因為兩批不相交；
    **若哪一輪相加不再等於總數，那個差額本身就是一項發現**，故此處現算。
    """
    try:
        gap = _n154.value("DEBT_OUTSTANDING") - _n154.value("DEBT_B4")
    except Exception:                                  # noqa: BLE001
        return NEEDS_EXEC
    if gap < 0:
        raise ValueError("🚨 影子尚欠項多於尚欠總數——⚠️ 兩格母體已不相容，"
                         "🚫 不得逕自相減後照印")
    return f"{gap}"


def catalogue():
    """自骨架現讀型錄。

    🚨 **🚫 不寫死型數**——⚠️ 本 run 每隔幾輪就新增一型，
    而寫死的數字不會跟著長（型錄自己的第 12 型）。

    ⚠️ 回傳 (列數, 型數, 誰抓到之分布)。
    **🚨 列數與型數不同**：有一列是舊型再現，🚫 不是新型。
    """
    t = SKELETON.read_text(encoding="utf-8")
    if CATALOGUE_HEADER not in t:
        raise ValueError("🚨 骨架中找不到型錄表頭——⚠️ 表格已改，🚫 不得逕自續用")
    blk = t.split(CATALOGUE_HEADER, 1)[1]
    rows = []
    for line in blk.split("\n"):
        line = line.strip()
        if not line:
            continue
        if not line.startswith("|"):
            break
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) >= 4 and not set(cells[0]) <= set("-: "):
            rows.append(cells)
    if not rows:
        raise ValueError("🚨 型錄表解析出 0 列——⚠️ 格式已變")

    # ⚠️ 「再現」列不計為新型：其編號欄不是純數字。
    kinds = [r for r in rows if r[0].strip().isdigit()]

    def who(s):
        # 🚨 「兩室各抓到一例」須先判——⚠️ 它含「室」字，
        # 若不先攔，會被整列算成「另一室抓到」，**而那不是事實**。
        if "兩室" in s:
            return "兩個工作室各抓到一例"
        if "自曝" in s:
            return "執行室自己招出來的"
        if "另一室" in s or "執行室" in s:
            return "另一個工作室抓到的"
        if "錯誤訊息" in s:
            return "程式自己噴錯攔下的"
        return "我自己回頭檢查發現的"

    return len(rows), len(kinds), Counter(who(r[2]) for r in rows)


